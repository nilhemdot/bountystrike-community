"""Phase 2 §10.4 dedup-recall fixture + measurement runner.

Produces a deterministic 1000-finding corpus with a labelled subset of
near-duplicate pairs, then drives an embedder of choice through the
semantic-dedup tier and reports recall on the labelled pairs.

Two embedders are supported via the ``Embedder`` protocol from
``dedup_mcp.embedding``:

  - :class:`BagOfWordsEmbedder` — deterministic, no network. Hashes
    each token into a 1536-dim sparse vector; cosine of overlapping
    token sets is high. Used in CI to validate the pipeline shape
    without OpenAI spend.
  - :class:`~dedup_mcp.embedding.OpenAIEmbedder` — production embedder.
    Used by the opt-in ``RUN_DEDUP_RECALL=1`` test for the actual
    Phase 2 §10.4 exit-criterion measurement.

The corpus is structured so the bag-of-words embedder catches the
labelled pairs at the ``≥0.85`` (T2) tier without false positives at
``≥0.75`` (display) on non-paired findings — verified by the
``test_runner_meets_recall_gate_with_fake_embedder`` end-to-end test.
"""

