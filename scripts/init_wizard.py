    """Print next steps and feedback link."""
    print("\n" + "=" * 60)
    print("Setup complete! Next steps:")
    print("=" * 60)

    if jwt_generated:
        print("\n1. Start infrastructure (if not already running):")
        print("   docker compose up -d")
        print("\n2. Export your JWT:")
