def main() -> int:
    parser = argparse.ArgumentParser(
        prog="init_wizard",
        description="Interactive onboarding wizard for BountyStrike v5",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--dry-run", action="store_true",
                       help="Show what would be written without writing files")
    parser.add_argument("--update", action="store_true",
                       help="Update existing configuration")
    args = parser.parse_args()

    print("=" * 60)
    print("BountyStrike v5 — Interactive Setup Wizard")
    print("=" * 60)

    existing = _load_existing_env()
    update_mode = args.update and bool(existing)

    if args.update and not existing:
        print("\nNo existing .env found. Running initial setup...\n")
        update_mode = False

    if update_mode:
        print(f"\nUpdate mode — {len(existing)} existing value(s) loaded from .env")
        print("You'll be asked whether to keep or change each value.")
        print("A backup will be created before any changes.\n")

    if existing and not args.update:
        print("\nExisting .env detected. Re-run with --update to modify.")
        if args.dry_run:
            print("Proceeding with JWT generation (dry-run mode)...\n")
        else:
            print("Continuing with JWT generation...\n")
        jwt_result = _generate_jwt(args.dry_run, auto_proceed=args.dry_run)

        # Offer first scan walkthrough if JWT was generated
        if jwt_result and "token" in jwt_result:
            database_url = existing.get("DATABASE_URL", "")
            if database_url:
                _offer_first_scan(jwt_result, database_url, args.dry_run)

        _show_next_steps(jwt_result is not None)
        return 0

    # Collect API keys
    env_vars = _collect_api_keys(existing, update_mode)
    _save_env(env_vars, args.dry_run)

    # Generate JWT
    jwt_result = _generate_jwt(args.dry_run)

    # Offer first scan walkthrough if JWT was generated
    if jwt_result and "token" in jwt_result:
        database_url = env_vars.get("DATABASE_URL", "")
        if database_url:
            _offer_first_scan(jwt_result, database_url, args.dry_run)

    # Show next steps
    _show_next_steps(jwt_result is not None)

    return 0


if __name__ == "__main__":
    sys.exit(main())
